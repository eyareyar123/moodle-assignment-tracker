export const STRINGS: Record<Lang, Record<Key, string>> = { en, he };

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Hebrew for Hebrew browsers, English otherwise; an explicit earlier choice wins. */
export function initialLang(saved: string | null, browserLangs: readonly string[]): Lang {
  if (saved === "en" || saved === "he") return saved;
  return browserLangs.some((l) => /^(he|iw)\b/i.test(l)) ? "he" : "en";
}
